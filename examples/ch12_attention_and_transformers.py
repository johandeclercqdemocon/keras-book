def block_5():
    import keras
    import numpy as np
    from keras import layers

    keras.utils.set_random_seed(0)

    layer = layers.MultiHeadAttention(num_heads=2, key_dim=8)
    layer(np.zeros((1, 6, 16), dtype="float32"), np.zeros((1, 6, 16), dtype="float32"))
    for weight in layer.weights:
        print(f"{weight.path:30s} {tuple(weight.shape)}")

    d, heads, key = 16, 2, 8
    by_hand = 3 * (d * heads * key + heads * key) + (heads * key * d + d)
    print("by hand:", by_hand, " layer:", layer.count_params())
    layer(np.zeros((1, 10, 16), dtype="float32"), np.zeros((1, 10, 16), dtype="float32"))
    print("after a call with 10 tokens instead of 6:", layer.count_params())


