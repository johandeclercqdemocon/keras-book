def block_1():
    import numpy as np
    from keras import ops

    rng = np.random.default_rng(2)
    q = rng.normal(size=(1, 5, 2, 8)).astype("float32")

    built_in = ops.convert_to_numpy(ops.dot_product_attention(q, q, q))

    scores = np.einsum("bthd,bshd->bhts", q, q) / np.sqrt(q.shape[-1])
    weights = np.exp(scores - scores.max(-1, keepdims=True))
    weights /= weights.sum(-1, keepdims=True)
    by_hand = np.einsum("bhts,bshd->bthd", weights, q)

    print("weights shape (batch, heads, query, key):", weights.shape)
    print("each row of weights sums to 1:", bool(np.allclose(weights.sum(-1), 1.0)))
    print("by hand equals keras.ops below 1e-5:", bool(np.abs(by_hand - built_in).max() < 1e-5))


