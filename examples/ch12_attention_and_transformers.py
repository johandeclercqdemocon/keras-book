def block_4():
    import keras
    import numpy as np
    from keras import layers, ops

    rng = np.random.default_rng(0)

    def make(n, length=16, vocabulary=10):
        x = rng.integers(3, vocabulary, size=(n, length))
        positions = np.array([rng.permutation(length)[:2] for _ in range(n)])
        x[np.arange(n), positions[:, 0]] = 1
        x[np.arange(n), positions[:, 1]] = 2
        return x.astype("int32"), (positions[:, 0] < positions[:, 1]).astype("int32")

    x_train, y_train = make(6000)
    x_test, y_test = make(2000)

    class TransformerBlock(layers.Layer):
        def __init__(self, width, heads, hidden, **kwargs):
            super().__init__(**kwargs)
            self.attention = layers.MultiHeadAttention(num_heads=heads, key_dim=width // heads)
            self.norm_1 = layers.LayerNormalization()
            self.feed_forward = keras.Sequential([layers.Dense(hidden, activation="relu"), layers.Dense(width)])
            self.norm_2 = layers.LayerNormalization()

        def call(self, x):
            x = self.norm_1(x + self.attention(x, x))
            return self.norm_2(x + self.feed_forward(x))

    class AddPositions(layers.Layer):
        def __init__(self, length, width, **kwargs):
            super().__init__(**kwargs)
            self.table = layers.Embedding(length, width)

        def call(self, x):
            return x + self.table(ops.arange(ops.shape(x)[1]))

    def build(positions, width=32):
        keras.utils.set_random_seed(0)
        tokens = keras.Input((16,), dtype="int32")
        x = layers.Embedding(10, width)(tokens)
        if positions == "outside a layer":
            x = x + layers.Embedding(16, width)(ops.arange(16))
        elif positions == "inside a layer":
            x = AddPositions(16, width)(x)
        x = TransformerBlock(width, heads=2, hidden=64)(x)
        x = layers.GlobalAveragePooling1D()(x)
        model = keras.Model(tokens, layers.Dense(1)(x))
        model.compile("adam", keras.losses.BinaryCrossentropy(from_logits=True),
                      metrics=[keras.metrics.BinaryAccuracy(threshold=0.0, name="acc")])
        return model

    print(f"{'positions':16s} {'weights':>8s} {'train acc':>10s} {'test acc':>9s}")
    for positions in ("none", "outside a layer", "inside a layer"):
        model = build(positions)
        h = model.fit(x_train, y_train, epochs=30, batch_size=64,
                      validation_data=(x_test, y_test), verbose=0).history
        print(f"{positions:16s} {model.count_params():8d} {h['acc'][-1]:10.3f} {h['val_acc'][-1]:9.3f}")


