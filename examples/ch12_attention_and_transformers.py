def block_2():
    import keras
    import numpy as np
    from keras import layers, ops

    keras.utils.set_random_seed(0)

    attention = layers.MultiHeadAttention(num_heads=2, key_dim=8)
    x = np.random.default_rng(1).normal(size=(1, 6, 16)).astype("float32")

    output, scores = attention(x, x, return_attention_scores=True)
    print("output shape:", tuple(output.shape), " weights shape:", tuple(scores.shape))
    print("rows sum to 1:", bool(np.allclose(ops.convert_to_numpy(scores).sum(-1), 1.0, atol=1e-5)))

    order = np.array([3, 0, 5, 1, 4, 2])
    permuted = ops.convert_to_numpy(attention(x[:, order], x[:, order]))
    original = ops.convert_to_numpy(attention(x, x))
    print("permuted input gives permuted output:", bool(np.abs(permuted - original[:, order]).max() < 1e-5))

    changed = x.copy()
    changed[:, 4] += 1.0
    open_before = ops.convert_to_numpy(attention(x, x))
    open_after = ops.convert_to_numpy(attention(changed, changed))
    causal_before = ops.convert_to_numpy(attention(x, x, use_causal_mask=True))
    causal_after = ops.convert_to_numpy(attention(changed, changed, use_causal_mask=True))
    print("change token 4, outputs at positions 0-3:")
    print("  without mask moved by", round(float(np.abs(open_after[:, :4] - open_before[:, :4]).max()), 3))
    print("  with causal mask moved by", float(np.abs(causal_after[:, :4] - causal_before[:, :4]).max()))


