def block_3():
    import keras
    import numpy as np
    from keras import layers

    rng = np.random.default_rng(0)

    def make(n, length=16, vocabulary=10):
        x = rng.integers(3, vocabulary, size=(n, length))
        positions = np.array([rng.permutation(length)[:2] for _ in range(n)])
        x[np.arange(n), positions[:, 0]] = 1
        x[np.arange(n), positions[:, 1]] = 2
        return x.astype("int32"), (positions[:, 0] < positions[:, 1]).astype("int32"), positions

    x_train, y_train, _ = make(6000)
    x_test, y_test, test_positions = make(2000)
    print("share of label 1 in the test set:", round(float(y_test.mean()), 3))

    def build(kind):
        keras.utils.set_random_seed(0)
        stack = [keras.Input((16,), dtype="int32"), layers.Embedding(10, 16)]
        if kind == "bag":
            stack += [layers.GlobalAveragePooling1D(), layers.Dense(32, activation="relu")]
        elif kind == "flatten":
            stack += [layers.Flatten(), layers.Dense(64, activation="relu")]
        elif kind == "conv":
            stack += [layers.Conv1D(32, 3, activation="relu"), layers.GlobalMaxPooling1D(),
                      layers.Dense(32, activation="relu")]
        elif kind == "simple rnn":
            stack += [layers.SimpleRNN(32)]
        elif kind == "gru":
            stack += [layers.GRU(32)]
        elif kind == "lstm":
            stack += [layers.LSTM(32)]
        stack.append(layers.Dense(1))
        model = keras.Sequential(stack)
        model.compile("adam", keras.losses.BinaryCrossentropy(from_logits=True),
                      metrics=[keras.metrics.BinaryAccuracy(threshold=0.0, name="acc")])
        return model

    models = {}
    print(f"{'model':11s} {'weights':>8s} {'train acc':>10s} {'test acc':>9s}")
    for kind in ("bag", "flatten", "conv", "simple rnn", "gru", "lstm"):
        models[kind] = build(kind)
        history = models[kind].fit(x_train, y_train, epochs=15, batch_size=64,
                                   validation_data=(x_test, y_test), verbose=0).history
        print(f"{kind:11s} {models[kind].count_params():8d} {history['acc'][-1]:10.3f} {history['val_acc'][-1]:9.3f}")


