def block_6():
    import keras
    import numpy as np
    from keras import layers

    keras.utils.set_random_seed(0)

    embedding = layers.Embedding(10, 4)
    tokens = np.array([[3, 1, 4, 1]])
    embedding(tokens)
    table = embedding.get_weights()[0]

    lookup = table[tokens]
    one_hot = np.eye(10)[tokens] @ table
    print("table shape:", table.shape, " weights:", embedding.count_params())
    print("lookup equals one-hot times table:", bool(np.allclose(lookup, one_hot, atol=1e-6)))
    print("same id at two positions gives the same row:", bool(np.array_equal(lookup[0, 1], lookup[0, 3])))



