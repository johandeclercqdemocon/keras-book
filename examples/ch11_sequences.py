def block_4():
    import keras
    import numpy as np
    from keras import layers

    rng = np.random.default_rng(0)

    def make(n, length=16, vocabulary=10):
        x = rng.integers(3, vocabulary, size=(n, length))
        positions = np.array([rng.permutation(length)[:2] for _ in range(n)])
        x[np.arange(n), positions[:, 0]] = 1
        x[np.arange(n), positions[:, 1]] = 2
        return x.astype("int32"), (positions[:, 0] < positions[:, 1]).astype("int32"), positions

    x_train, y_train, _ = make(6000)
    x_test, y_test, positions = make(2000)
    distance = np.abs(positions[:, 0] - positions[:, 1])

    def train(kind):
        keras.utils.set_random_seed(0)
        stack = [keras.Input((16,), dtype="int32"), layers.Embedding(10, 16)]
        if kind == "conv":
            stack += [layers.Conv1D(32, 3, activation="relu"), layers.GlobalMaxPooling1D(),
                      layers.Dense(32, activation="relu")]
        else:
            stack += [layers.GRU(32)]
        model = keras.Sequential(stack + [layers.Dense(1)])
        model.compile("adam", keras.losses.BinaryCrossentropy(from_logits=True))
        model.fit(x_train, y_train, epochs=15, batch_size=64, verbose=0)
        return (model.predict(x_test, verbose=0)[:, 0] > 0).astype("int32")

    predictions = {kind: train(kind) for kind in ("conv", "gru")}
    print(f"{'distance':>9s} {'pairs':>6s} {'conv':>7s} {'gru':>7s}")
    for low, high in [(1, 2), (3, 4), (5, 8), (9, 15)]:
        chosen = (distance >= low) & (distance <= high)
        scores = [float((predictions[k][chosen] == y_test[chosen]).mean()) for k in ("conv", "gru")]
        print(f"{low:3d} to {high:2d} {int(chosen.sum()):6d} {scores[0]:7.3f} {scores[1]:7.3f}")


