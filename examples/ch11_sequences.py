def block_5():
    import keras
    import numpy as np
    from keras import layers, ops

    plain = np.array([[3, 4, 5]])
    padded = np.array([[3, 4, 5, 0, 0]])

    for mask_zero in (False, True):
        keras.utils.set_random_seed(0)
        model = keras.Sequential([
            keras.Input((None,), dtype="int32"),
            layers.Embedding(10, 8, mask_zero=mask_zero),
            layers.GRU(4),
        ])
        difference = np.abs(ops.convert_to_numpy(model(plain)) - ops.convert_to_numpy(model(padded))).max()
        print(f"mask_zero={mask_zero!s:5s} difference between plain and padded: {float(difference):.4f}")


