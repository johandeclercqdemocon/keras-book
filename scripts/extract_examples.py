"""Write examples/chNN_<slug>.py from the python blocks of chapters/NN-<slug>.md.

The chapter is the source. The module is its blocks, in order, so that
`python -m examples.chNN_<slug>` reproduces every number the chapter prints.
Do not edit the modules by hand: this script overwrites them.

    python3 scripts/extract_examples.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
BLOCK = re.compile(r"```python\n(.*?)```", re.DOTALL)


def main() -> None:
    (ROOT / "examples").mkdir(exist_ok=True)
    for chapter in sorted((ROOT / "chapters").glob("[0-9][0-9]-*.md")):
        number, slug = chapter.stem.split("-", 1)
        blocks = BLOCK.findall(chapter.read_text(encoding="utf-8"))
        out = ROOT / "examples" / f"ch{number}_{slug.replace('-', '_')}.py"
        parts = [f'"""Every python block of chapters/{chapter.name}, in order.\n\n'
                 f'Generated by scripts/extract_examples.py. Edit the chapter, not this file.\n"""\n']
        for i, src in enumerate(blocks, 1):
            parts.append(f"\n# ---- block {i} " + "-" * 50 + "\n" + f"def block_{i}():\n"
                         + "".join(("    " + l if l.strip() else l) for l in src.splitlines(True)) + "\n")
        parts.append("\n\nif __name__ == \"__main__\":\n" + "".join(
            f"    print('--- block {i}')\n    block_{i}()\n" for i in range(1, len(blocks) + 1)))
        out.write_text("".join(parts), encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)} ({len(blocks)} blocks)")


if __name__ == "__main__":
    main()
